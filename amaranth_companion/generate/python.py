"""Emitting a design as an Amaranth package.

The mapping from canvas to code is deliberately dull, because the generated
file is something a user reads, diffs and checks into git:

* a **code block** is emitted verbatim -- its source *is* the Amaranth, so the
  generator never rewrites it, only decides where it goes and what it is
  called
* a **hierarchical block** becomes an ``Elaboratable`` whose ``elaborate``
  instantiates its children as submodules and wires them with ``m.d.comb``
* a **port block** becomes a ``Signal`` on that class, reached as ``self.x_in``
* a **variable block** becomes a module-level constant
* a **parameter edge** is not a wire: it becomes a constructor argument, which
  is the whole reason parameters are a separate kind of socket

Blocks with identical implementations share one generated class, keyed on the
structure of their child graph rather than on which definition they came from
-- two AND gates emit one class, but an AND gate whose insides have been edited
emits its own.
"""

import json
from logging import getLogger
from typing import Any, Iterable, Mapping, TYPE_CHECKING

from ..blocks.definition import BlockKind
from ..blocks.introspect import introspect_cached
from ..module.naming import family_name
from ..module.parameters import (
    module_variables,
    resolve_params,
    source_socket,
    variable_name,
)
from .names import NameAllocator, class_name, identifier

if TYPE_CHECKING:
    from ..design import Design
    from ..module import Module
    from ..module.element import Node, Socket

log = getLogger(__name__)

HEADER = '"""Generated by amaranth-companion. Edit the design, not this file."""'

#: the simulator is copied into the generated package rather than imported
#: from amaranth-companion, so `python -m <package>` works without it
WAVEFORM_MODULE = "_waveform"

#: the hardware half, copied in for the same reason as the simulator
HARDWARE_MODULE = "_hardware"

#: what `python -m <package>` does. Simulating is the default because it needs
#: nothing installed; `build` is the one that wants a toolchain and a board.
MAIN_TEMPLATE = """{header}

import sys

from .{hardware} import main as build_main
from .{waveform} import main as simulate_main
from .{module} import {top}

#: the board this design was drawn for, overridable with `build --platform`
PLATFORM = {platform!r}

if __name__ == "__main__":
    argv = sys.argv[1:]

    if argv[:1] == ["build"]:
        raise SystemExit(build_main({top}, "{package}", PLATFORM, argv[1:]))

    if argv[:1] == ["simulate"]:
        argv = argv[1:]
    raise SystemExit(simulate_main({top}, "{package}", argv))
"""

INDENT = "    "


class GenerationError(ValueError):
    """The design cannot be turned into code."""


def _indent(text: str, levels: int = 1) -> str:
    pad = INDENT * levels
    return "\n".join(pad + line if line.strip() else line for line in text.splitlines())


def _shape_expression(socket: "Socket", widths: Mapping[int, str]) -> str:
    """How to spell this socket's shape in a ``Signal(...)`` call.

    A width that matches one of the class's parameters is emitted as that
    parameter's name rather than the number it currently resolves to, so the
    generated class stays parameterisable instead of being frozen at whatever
    the canvas happened to show.
    """
    width = socket.shape.width
    spelling = widths.get(width, str(width))
    return f"signed({spelling})" if socket.shape.signed else spelling


class DesignGenerator:
    """Turns one :class:`~amaranth_companion.design.Design` into source."""

    def __init__(self, design: "Design", top_name: str = "Top") -> None:
        self._design = design
        self._top_name = top_name

        self._needs_io = False
        self._classes: list[str] = []
        self._emitted_code: dict[str, str] = {}
        self._emitted_blocks: dict[str, str] = {}
        # names the generated file already binds by importing amaranth; the
        # top class's own name is not among them, or it would be suffixed
        self._names = NameAllocator(
            reserved={"Module", "Signal", "Elaboratable", "Const", "Cat", "signed"}
        )

    # --- entry points ------------------------------------------------------

    def source(self) -> str:
        """The whole design as one module's worth of Python."""
        self._classes.clear()
        self._emitted_code.clear()
        self._emitted_blocks.clear()
        self._needs_io = False

        top = self._emit_module(self._design.root, self._top_name, is_top=True)

        blocks = []

        constants = self._constants(self._design.root)
        if constants:
            blocks.append(constants)

        blocks += [block.rstrip() for block in self._classes]

        log.debug("generated %s with %d classes", top, len(self._classes))

        imports = "from amaranth import *"
        if self._needs_io:
            # only when something binds to a pin, so a simulation-only design
            # does not carry an import it never uses
            imports += "\nfrom amaranth.lib import io"

        # one blank line after the docstring, two between definitions
        return f"{HEADER}\n\n{imports}\n\n\n" + "\n\n\n".join(blocks) + "\n"

    @property
    def top_name(self) -> str:
        """The class the root graph is emitted as."""
        return self._top_name

    def class_for(self, module: "Module") -> str | None:
        """The class ``module`` was emitted as.

        Only meaningful after :meth:`source` has run. A testbench needs this:
        it sits beside an implementation and has to name the thing it drives.
        """
        return self._emitted_blocks.get(self._structure_key(module))

    def files(self, package: str) -> dict[str, str]:
        """The design as a package, laid out like the amaranth-examples repo."""
        import inspect

        from ..verify import hardware, waveform
        from .tests import test_files

        module_name = identifier(package, "design")
        files = {
            f"{package}/__init__.py": f"from .{module_name} import *\n",
            f"{package}/{module_name}.py": self.source(),
            f"{package}/{WAVEFORM_MODULE}.py": inspect.getsource(waveform),
            f"{package}/{HARDWARE_MODULE}.py": inspect.getsource(hardware),
            f"{package}/__main__.py": MAIN_TEMPLATE.format(
                header=HEADER,
                waveform=WAVEFORM_MODULE,
                hardware=HARDWARE_MODULE,
                module=module_name,
                top=self._top_name,
                package=package,
                platform=self._design.platform or "",
            ),
        }
        # after `source()`, so the test generator can ask what each graph
        # was emitted as
        files.update(test_files(self._design, self, package))
        return files

    # --- variables ---------------------------------------------------------

    def _constants(self, module: "Module") -> str:
        """Variable blocks, as module-level constants in declaration order."""
        values = module_variables(module)
        if not values:
            return ""

        return "\n".join(
            f"{identifier(name)} = {value!r}" for name, value in values.items()
        )

    # --- modules -----------------------------------------------------------

    def _structure_key(self, module: "Module") -> str:
        """What makes two implementations the same implementation.

        Identity is not part of it. Every instance of a block is loaded with
        fresh uuids, so comparing the documents as they stand would call two
        copies of the same gate different implementations and emit the class
        twice. The uuids are numbered off by the order they appear in, which
        is the order the implementation file lists them in and so the same for
        every instance.
        """
        data = module.to_dict(versioned=False)
        # insertion order, not sorted: the numbering below is positional, and
        # sorting by uuid would shuffle two instances differently
        key = json.dumps(data)

        for index, uuid in enumerate(data.get("nodes", {})):
            key = key.replace(uuid, f"node{index}")
        return key

    def _emit_module(
        self, module: "Module", preferred: str, *, is_top: bool = False
    ) -> str:
        """Emit an ``Elaboratable`` for ``module``; returns its class name."""
        key = self._structure_key(module)
        if key in self._emitted_blocks:
            return self._emitted_blocks[key]

        name = self._names.take(class_name(preferred))
        # registered before the body is built, so a block that somehow
        # contains itself fails as a recursion error rather than looping
        self._emitted_blocks[key] = name

        ports = self._module_ports(module)
        params = self._module_params(module, is_top=is_top)
        instances = self._emit_children(module)

        self._classes.append(self._render_class(name, ports, params, instances, module))
        return name

    @staticmethod
    def _module_ports(module: "Module") -> list["Node"]:
        """The port blocks in ``module``, in the order their sockets sit."""
        return [
            node
            for node in module.nodes.values()
            if node.kind.is_port and list(node.sockets)
        ]

    def _module_params(self, module: "Module", *, is_top: bool) -> dict[str, Any]:
        """Constructor parameters for this module's class.

        Taken from the owning node, so a hierarchical block's declared
        parameters become the generated class's keyword arguments.
        """
        if is_top or module.owner is None:
            return {}

        values, _error = resolve_params(module.owner)
        return values

    def _emit_children(self, module: "Module") -> list[tuple[str, "Node", str]]:
        """Every node that becomes a submodule, as ``(instance, node, class)``."""
        instances: list[tuple[str, "Node", str]] = []
        local = NameAllocator(reserved={"m", "self", "platform"})

        for node in module.nodes.values():
            if node.kind is BlockKind.CODE:
                emitted = self._emit_code_block(node)
            elif node.kind is BlockKind.HIERARCHICAL and node.child_module is not None:
                # the class is named after the block, the instance after
                # this one of it: class AND, instances and0 and and1
                emitted = self._emit_module(node.child_module, family_name(node))
            else:
                continue  # port and variable blocks are not submodules

            instances.append((local.take(identifier(node.title)), node, emitted))

        return instances

    def _emit_code_block(self, node: "Node") -> str:
        """Emit a code block's source once; returns the class it defines."""
        source = node.text.strip()
        if not source:
            raise GenerationError(f"code block {node.title!r} is empty")

        if source in self._emitted_code:
            return self._emitted_code[source]

        params, _error = resolve_params(node)
        result = introspect_cached(source, params)
        if not result.ok:
            raise GenerationError(f"{node.title}: {result.error}")

        self._classes.append(self._strip_imports(source))
        self._emitted_code[source] = result.class_name
        self._names.take(result.class_name)
        return result.class_name

    @staticmethod
    def _strip_imports(source: str) -> str:
        """Drop the block's own ``from amaranth import *``.

        The generated file imports it once at the top; repeating it before
        every class is noise, and a star import inside the file would shadow
        anything declared above it.
        """
        kept = [
            line
            for line in source.splitlines()
            if line.strip() not in ("from amaranth import *", "import amaranth")
        ]
        return "\n".join(kept).strip() + "\n"

    # --- rendering ---------------------------------------------------------

    def _render_class(
        self,
        name: str,
        ports: list["Node"],
        params: Mapping[str, Any],
        instances: list[tuple[str, "Node", str]],
        module: "Module",
    ) -> str:
        param_names = {key: identifier(key) for key in params}

        signature = ", ".join(
            ["self"]
            + [f"{spelling}={params[key]!r}" for key, spelling in param_names.items()]
        )

        body = [f"def __init__({signature}):"]
        for key, spelling in param_names.items():
            body.append(f"{INDENT}self.{spelling} = {spelling}")

        # a parameter whose value is a plain integer can stand in for any
        # port width equal to it, which is what keeps `Signal(width_param)`
        # from collapsing into `Signal(1)`
        widths = {
            value: param_names[key]
            for key, value in params.items()
            if isinstance(value, int) and not isinstance(value, bool)
        }

        port_sockets = [
            socket for node in ports for socket in node.sockets if not socket.is_param
        ]
        for socket in port_sockets:
            body.append(
                f"{INDENT}self.{socket.name} = "
                f"Signal({_shape_expression(socket, widths)})"
            )

        # submodules are built here rather than in `elaborate`, so that a
        # formal spec beside this block can reach into `dut.counter` and
        # friends. It is also what `Top` in the blink example does.
        for instance, node, emitted in instances:
            body.append(
                f"{INDENT}self.{instance} = {emitted}"
                f"({self._instance_arguments(node)})"
            )
        lines = [f"class {name}(Elaboratable):"]
        # a class with no parameters, ports or submodules needs no constructor
        # at all; an empty one with `pass` in it is just noise in the output
        if len(body) > 1:
            lines.append(_indent("\n".join(body)))
            lines.append("")

        if port_sockets:
            lines += [
                _indent("@property\ndef ports(self):"),
                _indent(
                    "return ["
                    + ", ".join(f"self.{s.name}" for s in port_sockets)
                    + "]",
                    2,
                ),
                "",
            ]

        lines.append(_indent(self._render_elaborate(instances, module)))
        return "\n".join(lines) + "\n"

    def _render_elaborate(
        self, instances: list[tuple[str, "Node", str]], module: "Module"
    ) -> str:
        lines = ["def elaborate(self, platform):", f"{INDENT}m = Module()"]

        for instance, _node, _emitted in instances:
            lines.append(f"{INDENT}m.submodules.{instance} = self.{instance}")

        connections = list(self._render_connections(instances, module))
        if connections:
            lines.append("")
            lines += [f"{INDENT}{line}" for line in connections]

        bindings = list(self._render_platform_bindings(instances, module))
        if bindings:
            # guarded, because the same design is simulated and proved with no
            # platform at all, and `platform.request` would fail there
            lines += ["", f"{INDENT}if platform is not None:"]
            lines += [f"{INDENT * 2}{line}" for line in bindings]

        lines += ["", f"{INDENT}return m"]
        return "\n".join(lines)

    def _instance_arguments(self, node: "Node") -> str:
        """Parameter values to construct a submodule with.

        A parameter edge keeps its source in the generated call: fed from a
        port block it becomes ``self.width_param``, from a variable the
        constant's name. Only an unconnected parameter falls back to the
        literal it currently resolves to -- otherwise generating the file
        would quietly freeze a parameterisable design.
        """
        parts = []
        for name, socket in node.input_sockets.items():
            if not socket.is_param:
                continue
            expression = self._param_expression(socket)
            if expression is not None:
                parts.append(f"{identifier(name)}={expression}")
        return ", ".join(parts)

    def _param_expression(self, socket: "Socket") -> str | None:
        feeding = source_socket(socket)

        if feeding is not None:
            source_node = feeding.node
            if source_node.kind.is_port:
                return f"self.{feeding.name}"
            if source_node.kind is BlockKind.VARIABLE:
                return identifier(variable_name(source_node))

        values, _error = resolve_params(socket.node)
        value = values.get(socket.name)
        return None if value is None else repr(value)

    def _render_connections(
        self, instances: list[tuple[str, "Node", str]], module: "Module"
    ) -> Iterable[str]:
        """One ``m.d.comb`` assignment per signal edge, destination first."""
        by_node = {node.uuid: instance for instance, node, _ in instances}

        for edge in module.edges:
            start, end = edge.start_socket, edge.end_socket
            if start.is_param or end.is_param:
                continue  # a parameter is a constructor argument, not a wire

            source = self._expression(start, by_node)
            sink = self._expression(end, by_node)
            if source is None or sink is None:
                log.debug("skipping unroutable edge %s -> %s", start, end)
                continue

            yield f"m.d.comb += {sink}.eq({source})"

    def _render_platform_bindings(
        self, instances: list[tuple[str, "Node", str]], module: "Module"
    ) -> Iterable[str]:
        """Attach the design to the board's pins.

        Every binding goes through ``io.Buffer`` over a raw port, which is the
        one idiom that works for both a requested resource and a port the
        platform hands out ready-made.
        """
        from ..platforms import IOKind, effective_direction, find_io, parse_io
        from ..platforms import NAMED_PORTS_ATTRIBUTE

        by_node = {node.uuid: instance for instance, node, _ in instances}
        platform_id = self._design.platform
        local = NameAllocator(reserved={"m", "self", "platform"})

        for node in module.nodes.values():
            if node.kind is not BlockKind.RESOURCE:
                continue

            socket = next(iter(node.sockets), None)
            if socket is None or not socket.edges:
                log.debug("resource block %r is not connected", node.title)
                continue

            io_id, requested = parse_io(node.text)
            spec = find_io(platform_id, io_id) if platform_id else None
            direction = effective_direction(spec, requested)

            port = self._port_expression(spec, io_id, NAMED_PORTS_ATTRIBUTE)
            buffer = local.take(identifier(io_id, "pin"))
            self._needs_io = True

            yield (
                f"m.submodules.{buffer} = {buffer} = "
                f'io.Buffer("{direction}", {port})'
            )

            edge = socket.edges[0]
            if direction == "o":
                source = self._expression(edge.start_socket, by_node)
                if source is not None:
                    yield f"m.d.comb += {buffer}.o.eq({source})"
            else:
                sink = self._expression(edge.end_socket, by_node)
                if sink is not None:
                    yield f"m.d.comb += {sink}.eq({buffer}.i)"

    @staticmethod
    def _port_expression(spec, io_id: str, attribute: str) -> str:
        """How the generated code reaches the pin behind ``io_id``."""
        from ..platforms import IOKind

        if spec is not None and spec.kind is IOKind.REQUEST:
            return f'platform.request("{spec.name}", {spec.number}, dir="-")'
        return f'platform.{attribute}["{io_id}"]'

    @staticmethod
    def _expression(socket: "Socket", by_node: Mapping[str, str]) -> str | None:
        """How to name ``socket`` inside ``elaborate``."""
        node = socket.node

        if node.kind.is_port:
            # a port block is this class's own signal, not a submodule's
            return f"self.{socket.name}"

        instance = by_node.get(node.uuid)
        return f"self.{instance}.{socket.name}" if instance else None


def generate_source(design: "Design", top_name: str = "Top") -> str:
    """The design as Python source."""
    return DesignGenerator(design, top_name).source()


def generate_files(design: "Design", package: str) -> dict[str, str]:
    """The design as a package: path relative to the output root -> content."""
    return DesignGenerator(design).files(package)
