"""Emitting testbench blocks as a pytest file.

The same block that runs inside the editor is written out as an ordinary test,
so a design's tests are something you can run in CI without the editor
anywhere near them -- which is the shape the amaranth-examples repository
already has, with ``blink/tests/test_blink.py`` beside ``blink/blink.py``.

Each block's coroutine is emitted *inside* its test function rather than at
module level: two testbench blocks both define ``async def testbench``, and
nesting them keeps that from being a collision instead of renaming the user's
function behind their back.
"""

import inspect
from logging import getLogger
from textwrap import indent
from typing import TYPE_CHECKING

from ..blocks.definition import BlockKind
from ..verify import sby
from ..verify.formal import declared_modes
from .names import NameAllocator, identifier

if TYPE_CHECKING:
    from ..design import Design
    from ..module.element import Node

log = getLogger(__name__)

INDENT = "    "

HEADER = '"""Generated by amaranth-companion. Edit the design, not this file."""'

#: added to the generated file so a clocked design is driven and a purely
#: combinational one is not, without the generator having to elaborate
CLOCK_HELPER = '''def _add_clock(simulator, period=1e-6):
    """Drive `sync` if the design has one.

    A fragment reports no domains until the simulator has elaborated it, so
    asking is the only reliable check; a comb-only design has no clock.
    """
    try:
        simulator.add_clock(period)
    except NameError:
        pass
'''


#: the prover is copied into the generated package rather than imported from
#: amaranth-companion, so a design's tests run in CI without the editor
FORMAL_MODULE = "_formal"


def _formal_function(name: str, target: str, body: str, mode: str, depth: int) -> str:
    return (
        "@pytest.mark.skipif(\n"
        f"{INDENT}not formal_tools_available(), "
        'reason="formal verification needs sby and yosys"\n'
        ")\n"
        f"def test_{name}_{mode}():\n"
        + indent(body.strip(), INDENT)
        + "\n\n"
        + f"{INDENT}assert_formal({target}(), formal, "
        f'mode="{mode}", depth={depth})\n'
    )


def _test_function(name: str, target: str, body: str) -> str:
    return (
        f"def test_{name}():\n"
        + indent(body.strip(), INDENT)
        + "\n\n"
        + f"{INDENT}dut = {target}()\n"
        + f"{INDENT}simulator = Simulator(dut)\n"
        + f"{INDENT}_add_clock(simulator)\n\n"
        + f"{INDENT}async def entry(ctx):\n"
        + f"{INDENT * 2}await testbench(ctx, dut)\n\n"
        + f"{INDENT}simulator.add_testbench(entry)\n"
        + f"{INDENT}simulator.run()\n"
    )


def generate_tests(design: "Design", generator, package: str) -> str | None:
    """The design's testbench and formal blocks as one pytest module.

    ``generator`` must already have produced its source, so that it can say
    which class each block's graph was emitted as. Returns ``None`` when the
    design has nothing to check, so the caller can skip writing the file.
    """
    module_name = identifier(package, "design")
    names = NameAllocator()
    simulations: list[str] = []
    proofs: list[str] = []
    targets: set[str] = set()

    for module in design.walk():
        for node in module.nodes.values():
            if node.kind not in (BlockKind.TESTBENCH, BlockKind.FORMAL):
                continue

            target = generator.class_for(module)
            if target is None:
                log.warning("%r checks nothing generated", node.title)
                continue

            targets.add(target)
            name = names.take(identifier(node.title, "check"))

            if node.kind is BlockKind.TESTBENCH:
                simulations.append(_test_function(name, target, node.text))
                continue

            # one test per mode, which is why the blink example has three
            modes, depth = declared_modes(node.text)
            proofs += [
                _formal_function(name, target, node.text, mode, depth) for mode in modes
            ]

    if not simulations and not proofs:
        return None

    imports = []
    if proofs:
        imports.append("import pytest")
    if simulations:
        imports.append("from amaranth.sim import Simulator")
    if proofs:
        imports.append(
            f"from .{FORMAL_MODULE} import assert_formal, formal_tools_available"
        )
    imports.append(f"from ..{module_name} import {', '.join(sorted(targets))}")

    blocks = [HEADER, "\n".join(imports)]
    if simulations:
        blocks.append(CLOCK_HELPER.rstrip())
    blocks += [function.rstrip() for function in simulations + proofs]
    return "\n\n\n".join(blocks) + "\n"


def test_files(design: "Design", generator, package: str) -> dict[str, str]:
    """The ``tests/`` half of a generated package, empty if there is nothing."""
    source = generate_tests(design, generator, package)
    if source is None:
        return {}

    files = {
        f"{package}/tests/__init__.py": "",
        f"{package}/tests/test_{identifier(package, 'design')}.py": source,
    }

    if formal_nodes(design):
        # verbatim, so the generated tests prove things without the editor
        files[f"{package}/tests/{FORMAL_MODULE}.py"] = inspect.getsource(sby)

    return files


def formal_nodes(design: "Design") -> list["Node"]:
    """Every formal block in the design, outermost first."""
    return [
        node
        for module in design.walk()
        for node in module.nodes.values()
        if node.kind is BlockKind.FORMAL
    ]


def testbench_nodes(design: "Design") -> list["Node"]:
    """Every testbench block in the design, outermost first."""
    return [
        node
        for module in design.walk()
        for node in module.nodes.values()
        if node.kind is BlockKind.TESTBENCH
    ]
